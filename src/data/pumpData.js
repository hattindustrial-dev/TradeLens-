// Search function
export function searchParts(query, pumpTypeId) {
  if (!query || query.trim().length < 1) return []
  const q = query.trim().toLowerCase()

  return PUMP_PARTS
    .filter(part => {
      if (pumpTypeId && !part.pumpTypes.includes(pumpTypeId)) return false
      const refMatch = part.refNumbers.some(r => r.toLowerCase().includes(q))
      const nameMatch = part.name.toLowerCase().includes(q)
      const aliasMatch = part.aliases.some(a => a.toLowerCase().includes(q))
      return refMatch || nameMatch || aliasMatch
    })
    .slice(0, 8)
}
